import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import peggy from "peggy";

const grammar = await readFile(new URL("../src/grammar.peggy", import.meta.url), "utf8");
const source = peggy.generate(grammar, { output: "source", format: "es" });
const formatted = execFileSync("biome", ["format", "--stdin-file-path=src/parser.js"], {
  input: `// biome-ignore-all lint: Generated by Peggy; edit grammar.peggy instead.\n${source}`,
  encoding: "utf8",
});
await writeFile(new URL("../src/parser.js", import.meta.url), formatted);
